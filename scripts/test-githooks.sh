#!/usr/bin/env bash
# I check that no AI attribution reaches a commit or a push: the shared
# checker .githooks/ai-attribution.sh, the commit-msg hook and the
# attribution step of the pre-push hook. Each hook runs in throwaway
# repositories with an isolated HOME, so my git config is never read.
# HOOKS_DIR points the fixture at another copy, for example the hooks before a fix.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
repo="$(pwd)"
hooks="$(cd "${HOOKS_DIR:-.githooks}" && pwd)"
checker="$hooks/ai-attribution.sh"

fixture="$(mktemp -d)"
trap 'rm -rf "$fixture"' EXIT
failures=0

fail() { printf 'FAIL  %s\n' "$*"; failures=$((failures + 1)); }

# flagged TEXT / allowed TEXT — the checker rejects or accepts one message.
flagged() { printf '%s\n' "$1" | bash "$checker" >/dev/null && fail "not flagged: $1" || true; }
allowed() { printf '%s\n' "$1" | bash "$checker" >/dev/null || fail "flagged: $1"; }

flagged 'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'
flagged 'Co-authored-by: Claude Opus 5.5 <noreply@anthropic.com>'
flagged '  co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>'
flagged 'Co-authored-by: Cursor Agent <cursoragent@cursor.com>'
flagged 'Co-authored-by: Codex <codex@openai.com>'
flagged '🤖 Generated with [Claude Code](https://claude.com/claude-code)'
flagged 'Generated by Codex'
flagged 'Written with an AI assistant.'
flagged 'Created using ChatGPT'
flagged 'Claude-Session: https://example.invalid/session/1'
flagged 'See https://claude.ai/code for details'

allowed 'Co-authored-by: Jane Doe <jane@example.com>'
allowed 'chore: improve Codex discovery and shared harness maintenance (#217)'
allowed 'AGENTS.md is generated by ai/scripts/sync.py for Codex.'
allowed 'BrandIcon draws single-colour logos (Claude, Codex, Gemini, Copilot).'
allowed 'Add "Open in AI harness" GUI action'
allowed 'The bindings are generated by wails build.'

# The history this script ships with is clean: a positive control that the
# patterns do not reject the commits I already wrote.
if ! git -C "$repo" log --format=%B HEAD | bash "$checker" >"$fixture/history"; then
    fail "the checker flags existing history:"
    sed 's/^/      /' "$fixture/history"
fi

# Throwaway repositories with an isolated identity and no global config.
export HOME="$fixture/home" GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL="$fixture/home/.gitconfig"
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_PREFIX GIT_COMMON_DIR GIT_OBJECT_DIRECTORY
mkdir -p "$HOME"
git config --global user.name 'Test User'
git config --global user.email 'test@example.invalid'
git config --global init.defaultBranch main
git config --global core.hooksPath "$hooks"

git init -q --bare "$fixture/remote.git"
git clone -q "$fixture/remote.git" "$fixture/work" 2>/dev/null
cd "$fixture/work"

# commit-msg: a clean message commits; an attribution trailer is refused.
echo one >file && git add file
git commit -q -m 'Add the file' || fail "commit-msg refused a clean message"
echo two >file
if git commit -q -am $'Change the file\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>' 2>"$fixture/err"; then
    fail "commit-msg accepted a Claude co-author trailer"
fi
grep -qF 'remove the AI attribution' "$fixture/err" || fail "commit-msg did not explain the refusal"
# A verbose commit shows the diff below the scissors line; text there is
# not part of the message.
printf 'Generated with [Claude Code](https://claude.com/claude-code)\n' >file
GIT_EDITOR='sed -i.bak 1s/^/Quote\ a\ footer\ in\ a\ file/' git commit -q -a -v 2>/dev/null \
    || fail "commit-msg read the verbose diff as part of the message"

# pre-push: a commit made with --no-verify cannot reach the remote.
git tag clean-tag
if ! git push -q origin clean-tag >"$fixture/out" 2>&1; then
    fail "pre-push refused a tag on clean commits: $(cat "$fixture/out")"
fi
echo three >file
git commit -q --no-verify -am $'Sneak a trailer in\n\nCo-authored-by: Claude Opus 5.5 <noreply@anthropic.com>'
git tag dirty-tag
if git push -q origin dirty-tag >"$fixture/out" 2>&1; then
    fail "pre-push accepted a commit with a Claude co-author trailer"
fi
grep -qF 'carries AI attribution' "$fixture/out" || fail "pre-push did not name the offending commit"
if git push -q origin HEAD:refs/heads/feature >"$fixture/out" 2>&1; then
    fail "pre-push accepted a branch with a Claude co-author trailer"
fi
grep -qF 'carries AI attribution' "$fixture/out" || fail "pre-push did not check the branch commits"
git reset -q --hard clean-tag
git tag -a -m $'Release\n\nGenerated with [Claude Code](https://claude.com/claude-code)' dirty-annotated
if git push -q origin dirty-annotated >"$fixture/out" 2>&1; then
    fail "pre-push accepted an annotated tag with an attribution footer"
fi
grep -qF 'tag message carries AI attribution' "$fixture/out" || fail "pre-push did not name the tag message"

if [[ $failures -gt 0 ]]; then
    printf '%d githooks check(s) failed\n' "$failures"
    exit 1
fi
echo "githooks: all checks passed"
