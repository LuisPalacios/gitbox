// Command gen turns the gitbox-server binaries that scripts/build-server.sh
// compiled into what package serverbin embeds: one gzip file per target and
// zz_generated.go, which records the build identity and pins each binary by
// the SHA-256 of its uncompressed bytes.
//
// It uses the standard library only, so the result is the same on every
// platform that builds GitboxApp, Windows under Git Bash included.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"github.com/LuisPalacios/gitbox/cmd/gui/serverbin"
)

const generatedFile = "zz_generated.go"

func main() {
	in := flag.String("in", "", "folder with the compiled gitbox-server-<os>-<arch>[.exe] binaries")
	out := flag.String("out", "", "folder of package serverbin")
	version := flag.String("version", "", "build version")
	commit := flag.String("commit", "", "build commit, the full SHA")
	targets := flag.String("targets", "", "comma-separated <os>/<arch> list")
	flag.Parse()
	if err := run(*in, *out, *version, *commit, *targets); err != nil {
		fmt.Fprintln(os.Stderr, "serverbin/gen:", err)
		os.Exit(1)
	}
}

var (
	commitRE  = regexp.MustCompile(`^[0-9a-f]{40}$`)
	versionRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._+-]*$`)
)

func run(in, out, version, commit, targets string) error {
	if in == "" || out == "" {
		return fmt.Errorf("-in and -out are required")
	}
	if !versionRE.MatchString(version) {
		return fmt.Errorf("unexpected version %q", version)
	}
	if !commitRE.MatchString(commit) {
		return fmt.Errorf("unexpected commit %q: want the full SHA", commit)
	}
	wanted, err := parseTargets(targets)
	if err != nil {
		return err
	}

	// What an earlier run left must not be embedded next to this run's.
	stale, err := filepath.Glob(filepath.Join(out, "gitbox-server-*.gz"))
	if err != nil {
		return err
	}
	for _, path := range append(stale, filepath.Join(out, generatedFile)) {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
	}

	table := make([]serverbin.Target, 0, len(wanted))
	for _, t := range wanted {
		name := strings.TrimSuffix(serverbin.FileName(t.OS, t.Arch), ".gz")
		binary, err := os.ReadFile(filepath.Join(in, name))
		if err != nil {
			return err
		}
		if len(binary) == 0 {
			return fmt.Errorf("%s is empty", name)
		}
		packed, err := compress(binary)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(out, name+".gz"), packed, 0o644); err != nil {
			return err
		}
		sum := sha256.Sum256(binary)
		t.Size, t.SHA256 = int64(len(binary)), hex.EncodeToString(sum[:])
		table = append(table, t)
		fmt.Printf("serverbin: %-14s %9d bytes, %8d compressed, sha256 %s\n", t.Name(), t.Size, len(packed), t.SHA256)
	}

	source, err := render(version, commit, table)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, generatedFile), source, 0o644)
}

// parseTargets returns the targets of a comma-separated list, in the order
// package serverbin reports them. Unknown and repeated targets are errors.
func parseTargets(list string) ([]serverbin.Target, error) {
	seen := make(map[string]bool)
	for name := range strings.SplitSeq(list, ",") {
		if !slices.Contains(serverbin.Supported, name) {
			return nil, fmt.Errorf("unknown target %q (known: %s)", name, strings.Join(serverbin.Supported, ", "))
		}
		if seen[name] {
			return nil, fmt.Errorf("target %q is listed twice", name)
		}
		seen[name] = true
	}
	var out []serverbin.Target
	for _, name := range serverbin.Supported {
		if seen[name] {
			goos, goarch, _ := strings.Cut(name, "/")
			out = append(out, serverbin.Target{OS: goos, Arch: goarch})
		}
	}
	return out, nil
}

// compress returns data as a gzip stream at the highest level. The header
// carries no name and no time, so the same bytes always give the same file.
func compress(data []byte) ([]byte, error) {
	var buf bytes.Buffer
	zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	if err != nil {
		return nil, err
	}
	if _, err := zw.Write(data); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

var generated = template.Must(template.New(generatedFile).Parse(`//go:build serverbin

// Code generated by cmd/gui/serverbin/gen from scripts/build-server.sh. DO NOT EDIT.

package serverbin

// The build these binaries come from. GitboxApp refuses remote mode unless
// it is the same as its own.
const (
	Version = {{printf "%q" .Version}}
	Commit  = {{printf "%q" .Commit}}
)

var table = []Target{
{{- range .Table}}
	{OS: {{printf "%q" .OS}}, Arch: {{printf "%q" .Arch}}, Size: {{.Size}}, SHA256: {{printf "%q" .SHA256}}},
{{- end}}
}
`))

// render returns the Go source of zz_generated.go, formatted.
func render(version, commit string, table []serverbin.Target) ([]byte, error) {
	var buf bytes.Buffer
	err := generated.Execute(&buf, struct {
		Version, Commit string
		Table           []serverbin.Target
	}{version, commit, table})
	if err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}
