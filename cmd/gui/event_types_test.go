func TestEventTypesGenerated(t *testing.T) {
	for name := range eventClass {
		if _, ok := eventPayloadTypes[name]; !ok {
			t.Fatalf("missing event DTO for %s", name)
		}
	}
	g := eventTypeGenerator{seen: map[reflect.Type]bool{}}
	g.typ(reflect.TypeFor[EventMetadata]())
	var events strings.Builder
	for _, name := range slices.Sorted(maps.Keys(eventPayloadTypes)) {
		if _, ok := eventClass[name]; !ok {
			t.Fatalf("unknown event DTO for %s", name)
		}
		payload := eventPayloadTypes[name]
		ts := "null"
		if payload != nil {
			ts = g.typ(payload)
			if payload.Kind() == reflect.Slice || payload.Kind() == reflect.Map {
				ts += " | null"
			}
		}
		fmt.Fprintf(&events, "  %q: %s;\n", name, ts)
	}
	const file = "frontend/src/lib/dto.generated.ts"
	output := "// Generated by go generate ./cmd/gui. DO NOT EDIT.\n\n" + g.decls.String() +
		"export interface Envelope<T> extends EventMetadata {\n  payload: T;\n}\n\n" +
		"export interface EventPayloads {\n" + events.String() + "}\n"
	if *writeEventTypes {
		if err := os.WriteFile(file, []byte(output), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(file)
	if err != nil || string(got) != output {
		t.Fatalf("%s is out of date. Run go generate ./cmd/gui", file)
	}
}

type eventTypeGenerator struct {
	seen  map[reflect.Type]bool
	decls strings.Builder
}

func (g *eventTypeGenerator) typ(typ reflect.Type) string {
	if typ == reflect.TypeFor[skipReason]() {
		return "boolean | string"
	}
	switch typ.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.String:
		return "string"
	case reflect.Int, reflect.Int64, reflect.Uint, reflect.Uint64, reflect.Float64:
		return "number"
	case reflect.Slice:
		return g.typ(typ.Elem()) + "[]"
	case reflect.Map:
		return "Record<" + g.typ(typ.Key()) + ", " + g.typ(typ.Elem()) + ">"
	case reflect.Pointer:
		return g.typ(typ.Elem())
	case reflect.Struct:
		name := typ.Name()
		if name == "" {
			return "{ " + strings.Join(g.fields(typ), " ") + " }"
		}
		if !g.seen[typ] {
			g.seen[typ] = true
			fields := g.fields(typ)
			fmt.Fprintf(&g.decls, "export interface %s {\n", name)
			for _, field := range fields {
				fmt.Fprintf(&g.decls, "  %s\n", field)
			}
			g.decls.WriteString("}\n\n")
		}
		return name
	default:
		panic("unsupported event field type: " + typ.String())
	}
}

func (g *eventTypeGenerator) fields(typ reflect.Type) []string {
	var fields []string
	for field := range typ.Fields() {
		name, options, _ := strings.Cut(field.Tag.Get("json"), ",")
		if name == "-" {
			continue
		}
		if field.Anonymous && name == "" {
			fields = append(fields, g.fields(field.Type)...)
			continue
		}
		if !field.IsExported() {
			continue
		}
		if name == "" {
			name = field.Name
		}
		if strings.Contains(options, "omitempty") || strings.Contains(options, "omitzero") {
			name += "?"
		}
		fields = append(fields, name+": "+g.typ(field.Type)+";")
	}
	return fields
}
